namespace Core.Model;

/// <summary>
/// 命令的执行形态（需求 FR-TAP-01~03）。
///
/// 只有"点按"与"按住"两种，是**固定集合**——
/// 按 NFR-11（AC-20），界面上必须是选择控件，不得手输。
///
/// 关于 <see cref="None"/>：鼠标移动 / 鼠标滚轮两类命令没有"按住"的物理含义
/// （指针位置与滚动量不是可保持的状态），故其形态取此值。
/// 它**不是**用户可选项，只在类型层面表示"该命令不适用执行形态"。
/// </summary>
public enum TapMode
{
    /// <summary>不适用执行形态（鼠标移动 / 滚轮命令）。</summary>
    None = 0,

    /// <summary>点按：按下后立即松开，按频率重复。</summary>
    Tap = 1,

    /// <summary>按住：一次按下后保持不松开，直到任务停止时由工具补发松开。</summary>
    Hold = 2,
}
